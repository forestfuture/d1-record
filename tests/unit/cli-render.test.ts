import { describe, expect, test } from "vite-plus/test";
import {
  fingerprintOf,
  renderBase,
  renderSchema,
  type ListedModel,
} from "../../cli/schema/render.ts";
import { schemaOf, type GeneratedTable } from "../../cli/schema/schema.ts";

function tablesOf(sql: string): GeneratedTable[] {
  const result = schemaOf([{ name: "0001_create.sql", sql }]);
  if (!result.ok) throw new Error(result.errors.join("\n"));
  return result.tables;
}

/** A database's schema to render: its tables, on the DB binding, with these Models. */
function schemaFor(tables: GeneratedTable[], models: ListedModel[] = []) {
  return { tables, binding: "DB", models };
}

describe("renderSchema: the generated schema.ts", () => {
  test("declares each table's attributes, and the binding with every table and Model", () => {
    const tables = tablesOf(`
      CREATE TABLE products (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        price_cents INTEGER NOT NULL DEFAULT 0,
        settings TEXT CHECK (json_valid(settings)),
        created_at DATETIME
      );
      CREATE TABLE line_items (code TEXT PRIMARY KEY, active BOOLEAN DEFAULT TRUE);
    `);

    expect(renderSchema(schemaFor(tables), "migrations/"))
      .toBe(`// Generated by \`d1-record schema\` from migrations/ — don't edit.
// schema: ${fingerprintOf(schemaFor(tables))}

/** line_items — last changed by 0001_create.sql */
export const lineItems = {
  code: { type: "string", null: false, generateId: true },
  active: { type: "boolean", default: () => true },
} as const;

/** products — last changed by 0001_create.sql */
export const products = {
  id: { type: "string", null: false, generateId: true },
  name: { type: "string", null: false },
  priceCents: { type: "integer", null: false, default: () => 0 },
  settings: "json",
  createdAt: "datetime",
} as const;

/** The database's binding, its tables (with their primary keys), and the Models built on them. */
export const schema = {
  binding: "DB",
  tables: {
    line_items: { attributes: lineItems, primaryKey: "code" },
    products: { attributes: products, primaryKey: "id" },
  },
  models: {},
} as const;
`);
  });

  test("adds each Model's attributes to its class, by its module, and lists the Models", () => {
    const tables = tablesOf(`CREATE TABLE posts (id INTEGER PRIMARY KEY, title TEXT);
      CREATE TABLE users (id INTEGER PRIMARY KEY);`);
    const models = [
      { className: "User", table: "users", module: "../models/user" },
      { className: "Post", table: "posts", module: "../models/post" },
      { className: "FeaturedUser", table: "users", module: "../models/user" },
    ];

    const source = renderSchema(schemaFor(tables, models), "migrations/");

    expect(source).toContain(
      'import type { TableAttributes } from "@forestfuture/d1-record";\n\n/** posts',
    );
    expect(source).toContain(
      '  models: { FeaturedUser: "users", Post: "posts", User: "users" },\n} as const;',
    );
    expect(source).toMatch(
      /\n\ndeclare module "\.\.\/models\/post" \{\n {2}interface Post extends TableAttributes<typeof posts, \(typeof Post\)\["attributes"\]> \{\}\n\}\n/,
    );
    expect(source).toContain(`declare module "../models/user" {
  interface FeaturedUser
    extends TableAttributes<typeof users, (typeof FeaturedUser)["attributes"]> {}
  interface User extends TableAttributes<typeof users, (typeof User)["attributes"]> {}
}
`);
  });

  test("a table named like a JavaScript keyword gets a name that's allowed", () => {
    const source = renderSchema(
      schemaFor(tablesOf('CREATE TABLE "default" (id INTEGER PRIMARY KEY)')),
      "migrations/",
    );

    expect(source).toContain("export const defaultTable = {");
    expect(source).toContain('    default: { attributes: defaultTable, primaryKey: "id" },');
  });

  test("the fingerprint changes with the schema or its Models, and only with them", () => {
    const first = schemaFor(tablesOf("CREATE TABLE t (id INTEGER PRIMARY KEY, a TEXT)"));
    const same = schemaFor(
      tablesOf("CREATE TABLE t (\n  id   INTEGER PRIMARY KEY,\n  a    TEXT\n)"),
    );
    const changed = schemaFor(tablesOf("CREATE TABLE t (id INTEGER PRIMARY KEY, a TEXT NOT NULL)"));
    const modeled = { ...first, models: [{ className: "T", table: "t", module: "./t" }] };

    expect(fingerprintOf(first)).toMatch(/^[0-9a-f]{12}$/);
    expect(fingerprintOf(same)).toBe(fingerprintOf(first));
    expect(fingerprintOf(changed)).not.toBe(fingerprintOf(first));
    expect(fingerprintOf(modeled)).not.toBe(fingerprintOf(first));
  });

  test("the fingerprint is the same whichever order the Models were found in", () => {
    const tables = tablesOf(
      "CREATE TABLE a (id INTEGER PRIMARY KEY); CREATE TABLE b (id INTEGER PRIMARY KEY);",
    );
    const a = { className: "A", table: "a", module: "./a" };
    const b = { className: "B", table: "b", module: "./b" };

    expect(fingerprintOf(schemaFor(tables, [b, a]))).toBe(fingerprintOf(schemaFor(tables, [a, b])));
  });

  test("names that aren't plain identifiers are quoted or made valid, and comments stay closed", () => {
    const source = renderSchema(
      schemaFor(
        tablesOf(`CREATE TABLE "2fa" (id INTEGER PRIMARY KEY, "first name" TEXT, "a-b" TEXT);
        CREATE TABLE "odd */ name" (id INTEGER PRIMARY KEY);`),
      ),
      "migrations/",
    );

    expect(source).toContain("export const table2fa = {");
    expect(source).toContain('  "first name": "string",');
    expect(source).toContain('  "a-b": "string",');
    expect(source).toContain("/** odd *\\/ name — last changed by 0001_create.sql */");
    expect(source).toContain("export const oddName = {");
  });

  test("defaults are written as functions: literals, JSON values and dates", () => {
    const source = renderSchema(
      schemaFor(
        tablesOf(`CREATE TABLE t (id INTEGER PRIMARY KEY,
        settings TEXT DEFAULT '{"a":1}' CHECK (json_valid(settings)),
        starts_at DATETIME DEFAULT '2026-01-01T00:00:00.000Z')`),
      ),
      "migrations/",
    );

    expect(source).toContain('  settings: { type: "json", default: () => ({ a: 1 }) },');
    expect(source).toContain(
      '  startsAt: { type: "datetime", default: () => new Date("2026-01-01T00:00:00.000Z") },',
    );
  });

  test("the app's base class holds the schema, named as Rails names it, and the app's to edit", () => {
    const source = renderBase("LogsRecord", "../db/LOGS");

    expect(source).toMatch(
      /^import \{ Model \} from "@forestfuture\/d1-record";\nimport \{ schema \} from "\.\.\/db\/LOGS";\n/,
    );
    expect(source).toContain("export abstract class LogsRecord extends Model {");
    expect(source).toContain("  static override schema = schema;");
    expect(source).not.toContain("modelFor");
  });

  // It comes from the project's paths, written into a string literal (#85).
  test("the schema's import path is written as an escaped string literal", () => {
    const source = renderBase("ApplicationRecord", '../db/a"b\\c');

    expect(source).toContain('import { schema } from "../db/a\\"b\\\\c";');
  });

  test("its shared method, scope and callback are there to uncomment, each saying what it does", () => {
    const source = renderBase("ApplicationRecord", "../db/schema");

    expect(source).toContain("  // A method every record has:\n  // label() {");
    expect(source).toContain(
      "  // static newest = this.scope((q) => q.order(sql`created_at DESC`));",
    );
    expect(source).toContain(
      "  // static override onQuery: QueryListener = ({ model, sql, durationMs }) =>",
    );
    expect(source).toContain(
      "    // A callback that runs for every Model, before each Model's own:\n    // this.beforeSave(",
    );
    expect(source).toContain(
      "  // How new TEXT keys are made (a UUID by default), e.g. time-ordered ones from a\n" +
        "  // library you choose:\n  // static override generateId = () => uuidv7();",
    );
  });
});
