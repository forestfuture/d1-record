import { describe, expect, test } from "vite-plus/test";
import { fingerprintOf, renderBase, renderSchema } from "../../cli/schema/render.ts";
import { schemaOf, type GeneratedTable } from "../../cli/schema/schema.ts";

function tablesOf(sql: string): GeneratedTable[] {
  const result = schemaOf([{ name: "0001_create.sql", sql }]);
  if (!result.ok) throw new Error(result.errors.join("\n"));
  return result.tables;
}

describe("renderSchema: the generated schema.ts", () => {
  test("declares each table's attributes, and every table with its key: a document, importing nothing", () => {
    const tables = tablesOf(`
      CREATE TABLE products (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        price_cents INTEGER NOT NULL DEFAULT 0,
        settings TEXT CHECK (json_valid(settings)),
        created_at DATETIME
      );
      CREATE TABLE line_items (code TEXT PRIMARY KEY, active BOOLEAN DEFAULT TRUE);
    `);

    expect(renderSchema(tables, "migrations/"))
      .toBe(`// Generated by \`d1-record schema\` from migrations/ — don't edit.
// schema: ${fingerprintOf(tables)}

/** line_items — last changed by 0001_create.sql */
export const lineItems = {
  code: { type: "string", null: false, generateId: true },
  active: { type: "boolean", default: () => true },
} as const;

/** products — last changed by 0001_create.sql */
export const products = {
  id: { type: "string", null: false, generateId: true },
  name: { type: "string", null: false },
  priceCents: { type: "integer", null: false, default: () => 0 },
  settings: "json",
  createdAt: "datetime",
} as const;

/** Every table, by name, with its attributes and primary key. */
export const tables = {
  line_items: { attributes: lineItems, primaryKey: "code" },
  products: { attributes: products, primaryKey: "id" },
} as const;
`);
  });

  test("a table named like a JavaScript keyword gets a name that's allowed", () => {
    const source = renderSchema(
      tablesOf('CREATE TABLE "default" (id INTEGER PRIMARY KEY)'),
      "migrations/",
    );

    expect(source).toContain("export const defaultTable = {");
    expect(source).toContain('  default: { attributes: defaultTable, primaryKey: "id" },');
  });

  test("the fingerprint changes with the schema, and only with it", () => {
    const first = tablesOf("CREATE TABLE t (id INTEGER PRIMARY KEY, a TEXT)");
    const same = tablesOf("CREATE TABLE t (\n  id   INTEGER PRIMARY KEY,\n  a    TEXT\n)");
    const changed = tablesOf("CREATE TABLE t (id INTEGER PRIMARY KEY, a TEXT NOT NULL)");

    expect(fingerprintOf(first)).toMatch(/^[0-9a-f]{12}$/);
    expect(fingerprintOf(same)).toBe(fingerprintOf(first));
    expect(fingerprintOf(changed)).not.toBe(fingerprintOf(first));
  });

  test("names that aren't plain identifiers are quoted or made valid, and comments stay closed", () => {
    const source = renderSchema(
      tablesOf(`CREATE TABLE "2fa" (id INTEGER PRIMARY KEY, "first name" TEXT, "a-b" TEXT);
        CREATE TABLE "odd */ name" (id INTEGER PRIMARY KEY);`),
      "migrations/",
    );

    expect(source).toContain("export const table2fa = {");
    expect(source).toContain('  "first name": "string",');
    expect(source).toContain('  "a-b": "string",');
    expect(source).toContain("/** odd *\\/ name — last changed by 0001_create.sql */");
    expect(source).toContain("export const oddName = {");
  });

  test("defaults are written as functions: literals, JSON values and dates", () => {
    const source = renderSchema(
      tablesOf(`CREATE TABLE t (id INTEGER PRIMARY KEY,
        settings TEXT DEFAULT '{"a":1}' CHECK (json_valid(settings)),
        starts_at DATETIME DEFAULT '2026-01-01T00:00:00.000Z')`),
      "migrations/",
    );

    expect(source).toContain('  settings: { type: "json", default: () => ({ a: 1 }) },');
    expect(source).toContain(
      '  startsAt: { type: "datetime", default: () => new Date("2026-01-01T00:00:00.000Z") },',
    );
  });

  test("the app's base class is built on the schema, named as Rails names it, and the app's to edit", () => {
    const source = renderBase("LogsRecord", "../db/LOGS", "LOGS");

    expect(source).toMatch(
      /^import \{ Model, modelFor \} from "@forestfuture\/d1-record";\nimport \{ tables \} from "\.\.\/db\/LOGS";\n/,
    );
    expect(source).toContain("class Base extends Model.Base {");
    expect(source).toContain('  static override binding = "LOGS";');
    expect(source).toContain("export const LogsRecord = modelFor(tables, Base);");
  });

  // Both come from the project's config and paths, written into string literals (#85).
  test("the binding and the schema's import path are written as escaped string literals", () => {
    const source = renderBase("ApplicationRecord", '../db/a"b\\c', 'D"B');

    expect(source).toContain('import { tables } from "../db/a\\"b\\\\c";');
    expect(source).toContain('  static override binding = "D\\"B";');
  });

  test("its shared method, scope and callback are there to uncomment, each saying what it does", () => {
    const source = renderBase("ApplicationRecord", "../db/schema", "DB");

    expect(source).toContain("  // A method every record has:\n  // label() {");
    expect(source).toContain(
      "  // static newest = this.scope((q) => q.order(sql`created_at DESC`));",
    );
    expect(source).toContain(
      "  // static override onQuery: QueryListener = ({ model, sql, durationMs }) =>",
    );
    expect(source).toContain(
      "    // A callback that runs for every Model, before each Model's own:\n    // this.beforeSave(",
    );
  });
});
