import { describe, expect, test } from "vite-plus/test";
import { planGenerate } from "../../cli/generate/command.ts";
import { planSchema } from "../../cli/schema/command.ts";
import type { DatabaseSnapshot, ProjectSnapshot } from "../../cli/schema/snapshot.ts";

const cwd = "/app";

/** A project with one database, `DB`, as `readProject` would read it from disk. */
function project(database: Partial<DatabaseSnapshot> = {}): ProjectSnapshot {
  return {
    cwd,
    files: new Map(),
    databases: [
      {
        target: {
          database: { binding: "DB", databaseName: "my-app-db", migrationsDir: "migrations" },
          configDir: cwd,
          migrationsDir: `${cwd}/migrations`,
          out: `${cwd}/src/db/schema.ts`,
          base: { path: `${cwd}/src/models/application-record.ts`, className: "ApplicationRecord" },
        },
        migrations: [{ name: "0001_users.sql", sql: "CREATE TABLE users (id TEXT PRIMARY KEY);" }],
        schemaFolder: false,
        base: false,
        nestedMigrations: false,
        toolFiles: [],
        ...database,
      },
    ],
  };
}

describe("planSchema: what d1-record schema writes and prints, from a snapshot", () => {
  test("a new project gets its schema and its base class", () => {
    const plan = planSchema(project(), false);

    expect(plan.files.map((file) => file.path)).toEqual([
      `${cwd}/src/db/schema.ts`,
      `${cwd}/src/models/application-record.ts`,
    ]);
    expect(plan.lines).toEqual([
      "Wrote src/db/schema.ts (1 table) from migrations/",
      "Wrote src/models/application-record.ts",
    ]);
    expect(plan.code).toBe(0);
  });

  test("a schema file d1-record didn't write is left alone, and nothing is written", () => {
    const plan = planSchema(project({ schema: "export const users = {};\n" }), false);

    expect(plan.files).toEqual([]);
    expect(plan.lines).toEqual([
      'src/db/schema.ts wasn\'t written by d1-record schema (it has no "Generated by" header), ' +
        "so it's left as it is; choose another file with --out, such as --out src/db/d1-record.ts",
      "Kept src/db/schema.ts as it was",
    ]);
    expect(plan.code).toBe(1);
  });

  test("a missing migrations folder writes nothing", () => {
    const plan = planSchema(project({ migrations: undefined }), false);

    expect(plan.lines).toEqual([
      "No migrations folder at migrations/",
      "Wrote nothing to src/db/schema.ts",
    ]);
    expect(plan.code).toBe(1);
  });

  test("with check, an up-to-date schema passes and nothing is written", () => {
    const written = planSchema(project(), false).files[0]!.source;
    const plan = planSchema(project({ schema: written, base: true }), true);

    expect(plan).toEqual({ files: [], lines: ["src/db/schema.ts is up to date"], code: 0 });
  });

  test("Drizzle's config files earn its notes with a new schema", () => {
    const plan = planSchema(project({ toolFiles: ["Drizzle"] }), false);

    expect(plan.lines.at(-1)).toMatch(/^Note: these migrations look like Drizzle's\./);
  });
});

describe("planGenerate: what g model and g migration write and print, from a snapshot", () => {
  const product = { kind: "model", name: "Product", columns: ["name:string!"] } as const;

  test("g model writes its migration, its Model, the schema, and the base class", () => {
    const plan = planGenerate(project(), product);

    expect(plan.files.map((file) => file.path)).toEqual([
      `${cwd}/migrations/0002_create_products.sql`,
      `${cwd}/src/models/product.ts`,
      `${cwd}/src/db/schema.ts`,
      `${cwd}/src/models/application-record.ts`,
    ]);
    expect(plan.lines).toEqual([
      "Wrote migrations/0002_create_products.sql",
      "Wrote src/models/product.ts",
      "Wrote src/db/schema.ts (2 tables) from migrations/",
      "Wrote src/models/application-record.ts",
      "Next: npx wrangler d1 migrations apply my-app-db --local",
    ]);
    expect(plan.code).toBe(0);
  });

  test("a Model file that already exists is refused, and nothing is written", () => {
    const existing = {
      ...project(),
      files: new Map([[`${cwd}/src/models/product.ts`, "// mine\n"]]),
    };
    const plan = planGenerate(existing, product);

    expect(plan).toEqual({
      files: [],
      lines: ["src/models/product.ts already exists", "Wrote nothing"],
      code: 1,
    });
  });

  test("a schema file d1-record didn't write is refused before anything else", () => {
    const plan = planGenerate(project({ schema: "export {};\n" }), {
      ...product,
      columns: ["x:nope"],
    });

    expect(plan.files).toEqual([]);
    expect(plan.lines[0]).toMatch(/^src\/db\/schema.ts wasn't written by d1-record schema/);
    expect(plan.lines.at(-1)).toBe("Wrote nothing");
  });
});
