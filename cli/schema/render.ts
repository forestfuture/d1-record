import { createHash } from "node:crypto";
import { camelize } from "../../src/naming.ts";
import type { Default, Spec } from "./conventions.ts";
import type { TableSchema } from "./schema.ts";

/** Words JavaScript doesn't allow as a `const` name. */
const reserved = new Set(
  (
    "break case catch class const continue debugger default delete do else enum export extends " +
    "false finally for function if import in instanceof new null return super switch this throw " +
    "true try typeof var void while with yield let static implements interface package private " +
    "protected public await arguments eval tables"
  ).split(" "),
);

/** The `const` a table is exported as: camelCase, and never a reserved word. */
function constName(table: string): string {
  const name = camelize(table.replace(/\W/g, "_"));
  return reserved.has(name) || /^\d/.test(name) ? `${name}Table` : name;
}

function defaultSource(value: Default): string {
  return "generated" in value
    ? "() => crypto.randomUUID()"
    : `() => ${JSON.stringify(value.literal)}`;
}

/** An attribute's spec: just its type when that's all it has, as Models are written by hand. */
function specSource(spec: Spec): string {
  const parts = [`type: ${JSON.stringify(spec.type)}`];
  if (spec.null === false) parts.push("null: false");
  if (spec.column !== undefined) parts.push(`column: ${JSON.stringify(spec.column)}`);
  if (spec.default !== undefined) parts.push(`default: ${defaultSource(spec.default)}`);
  return parts.length === 1 ? JSON.stringify(spec.type) : `{ ${parts.join(", ")} }`;
}

function tableSource(table: TableSchema): string {
  const attributes = Object.entries(table.attributes)
    .map(([name, spec]) => `  ${name}: ${specSource(spec)},`)
    .join("\n");
  return `/** ${table.name} — last changed by ${table.lastChangedBy} */
export const ${constName(table.name)} = {
${attributes}
} as const;`;
}

/** A short hash of the schema itself, so `--check` ignores how the file is formatted. */
export function fingerprintOf(tables: readonly TableSchema[]): string {
  return createHash("sha256").update(JSON.stringify(tables)).digest("hex").slice(0, 12);
}

/** The generated `schema.ts`: each table as `Model({...})` takes it, and every table by name. */
export function renderSchema(tables: readonly TableSchema[], source: string): string {
  const entries = tables
    .map((table) => {
      const key = /^[A-Za-z_$][\w$]*$/.test(table.name) ? table.name : JSON.stringify(table.name);
      return `  ${key}: { attributes: ${constName(table.name)}, primaryKey: ${JSON.stringify(table.primaryKey)} },`;
    })
    .join("\n");
  return `// Generated by \`d1-record schema\` from ${source} — don't edit.
// schema: ${fingerprintOf(tables)}

${tables.map(tableSource).join("\n\n")}

/** Every table, by name, with its attributes and primary key. */
export const tables = {
${entries}
} as const;
`;
}

/** The fingerprint a generated file was made from, read from its header. */
export function fingerprintIn(source: string): string | undefined {
  return /^\/\/ schema: ([0-9a-f]{12})$/m.exec(source)?.[1];
}
